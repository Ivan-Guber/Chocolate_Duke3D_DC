int DC_SaveToVMU(char* src, int tp) {
	char dst[32];
	file_t file;
	int filesize = 0;
	unsigned long zipsize = 0;
	uint8* data;
	uint8* zipdata;
	vmu_pkg_t pkg;
	uint8* pkg_out;
	int pkg_size;

	strcpy(dst, "/vmu/a1/");
	strcat(dst, src);
	file = fs_open(src, O_RDONLY);
	filesize = fs_total(file);
	data = (uint8*)malloc(filesize);
	fs_read(file, data, filesize);
	fs_close(file);

	zipsize = filesize * 1.5;
	zipdata = (uint8*)malloc(zipsize);
	compress(zipdata, &zipsize, data, filesize);

	strcpy(pkg.desc_short, "Duke 3D");

	strcpy(pkg.desc_long, "Game Save");

	strcpy(pkg.app_id, "Duke3D");
	pkg.icon_cnt = 1;
	pkg.icon_anim_speed = 0;

	memcpy(&pkg.icon_pal[0], vmu_icon_pal, 32);
	pkg.icon_data = vmu_icon_img;

	pkg.eyecatch_type = VMUPKG_EC_NONE;
	pkg.data_len = zipsize;
	pkg.data = zipdata;

	vmu_pkg_build(&pkg, &pkg_out, &pkg_size);

	fs_unlink(dst);
	file = fs_open(dst, O_WRONLY);

	if (pkg_size < 1024 * 72) pkg_size = 1024 * 72;
	
	fs_write(file, pkg_out, pkg_size);
	fs_vmu_set_header(file, &pkg);
	fs_close(file);

	free(pkg_out);
	free(data);
	free(zipdata);

	return 0;
}

