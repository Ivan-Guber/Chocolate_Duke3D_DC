int DC_LoadFromVMU(char* dst, int savefilesize) {
	char src[32];
	int file;
	int filesize;
	unsigned long unzipsize;
	uint8* data;
	uint8* unzipdata;
	vmu_pkg_t pkg;

	strcpy(src, "/vmu/a1/");
	strcat(src, dst);

	file = fs_open(src, O_RDONLY);
	if (file == 0) return -1;
	filesize = fs_total(file);
	if (filesize <= 0) return -1;
	data = (uint8*)malloc(filesize);
	fs_read(file, data, filesize);
	vmu_pkg_parse(data, filesize,&pkg);
	fs_close(file);

	unzipdata = (uint8*)malloc(savefilesize);
	unzipsize = savefilesize;

	uncompress(unzipdata, &unzipsize, (uint8*)pkg.data, pkg.data_len);
	fs_unlink(dst);
	file = fs_open(dst, O_WRONLY);
	fs_write(file, unzipdata, unzipsize);
	fs_close(file);

	free(data);
	free(unzipdata);

	return 0;
}

